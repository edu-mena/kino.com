/**
 * Modelos de cardápio para o painel do restaurante (`/admin/cardapio` →
 * "Gerir cardápios"). Cada categoria traz um nome por omissão e uma lista
 * de pratos-modelo típicos — ao criar um cardápio de uma categoria, o
 * gestor pode aceitar esses pratos como ponto de partida (edita/remove
 * depois como quaisquer outros). Contexto Angola/PALOP, preços em Kz
 * coerentes com o resto do dataset.
 *
 * O conteúdo dos pratos (nome, descrição) é *dados*, não interface — fica
 * em português, como o restante `mockData`. Os nomes das categorias, esses,
 * são traduzidos (`menuTypes` em `@/i18n`).
 */

